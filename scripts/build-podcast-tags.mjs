#!/usr/bin/env node
/**
 * build-podcast-tags.mjs
 *
 * Controlled topic + company tags for the podcast summaries of every show in
 * src/podcast-shows.mjs (NOT The AI Daily Brief, which keeps
 * scripts/build-ainews-tags.mjs), using the shared vocabulary
 * src/data/podcast-taxonomy.json.
 *
 * Per episode (staging file podcast-summaries/<show>/YYYY-MM-DD-slug.md):
 *   - extraction exists (<wiki>/<show>/extractions/<basename>.json):
 *     score its entities/concepts exactly like build-ainews-tags.mjs
 *     (central = 3, notable = 1, same thresholds)          -> source "extraction"
 *   - otherwise: conservative match of taxonomy names + keywords in the
 *     summary's title, description, thesis and key points  -> source "summary"
 *
 * Outputs (committed; the site build reads only these, never the wiki):
 *   src/data/podcast-tags.json         {"<show>/<basename>": ["topic", ..., "company", ...]}
 *   src/data/podcast-topic-stats.json  {tagSource: {"<show>/<basename>": "extraction"|"summary"},
 *                                       topics: {<tag>: {<show>: {extractionEpisodes, related: [...]}}}}
 *     `related` = the 3 most central entities/concepts (excluding the tag's own
 *     vocabulary and each show's hosts) across that show's tagged episodes;
 *     AIDB is included via src/data/ainews-tags.json + the root extractions.
 *
 * Re-running picks up new summaries and new extractions automatically.
 * Usage: node scripts/build-podcast-tags.mjs [--report]
 */
import fs from 'fs';
import path from 'path';
import { podcastShows } from '../src/podcast-shows.mjs';
import {
  ROOT, AIDB, taxonomy, wikiAvailable, readJson, listExtractions, readExtraction,
  tagsFromExtraction, tagsFromSummary, parseSummary, listStagedEpisodes, tagsOfName, showHosts, companyOf,
} from './lib/podcast-wiki.mjs';

const REPORT = process.argv.includes('--report');
const OUT_TAGS = path.join(ROOT, 'src/data/podcast-tags.json');
const OUT_STATS = path.join(ROOT, 'src/data/podcast-topic-stats.json');

if (!wikiAvailable) {
  console.error('Blog wiki not found; set PODCAST_WIKI_DIR. Refusing to overwrite tags with summary-only results.');
  process.exit(1);
}

const tags = {};
const tagSource = {};
const perShow = {};
// tag -> show -> [extraction items of tagged episodes]
const tagged = {};
const addTagged = (tag, show, items) => {
  ((tagged[tag] ??= {})[show] ??= []).push(items);
};

for (const show of podcastShows) {
  const st = (perShow[show.slug] = { episodes: 0, extraction: 0, summary: 0, untagged: 0 });
  for (const ep of listStagedEpisodes(show.slug)) {
    const key = `${show.slug}/${ep.basename}`;
    const ex = readExtraction(show.slug, ep.basename);
    let t;
    if (ex) {
      t = tagsFromExtraction(ex.items, parseSummary(ep.file));
      tagSource[key] = 'extraction';
      st.extraction++;
      for (const tag of t) addTagged(tag, show.slug, ex.items);
    } else {
      t = tagsFromSummary(parseSummary(ep.file));
      tagSource[key] = 'summary';
      st.summary++;
    }
    st.episodes++;
    if (!t.length) st.untagged++;
    tags[key] = t;
  }
}

// AIDB: membership from its own tag file (built by build-ainews-tags.mjs).
const aidbTags = readJson(path.join(ROOT, 'src/data/ainews-tags.json'), {});
for (const [basename, t] of Object.entries(aidbTags)) {
  const ex = readExtraction(AIDB, basename);
  if (!ex) continue;
  for (const tag of t) addTagged(tag, AIDB, ex.items);
}

const hostsOf = {};
for (const show of [AIDB, ...podcastShows.map((s) => s.slug)]) hostsOf[show] = showHosts(show);

const topics = {};
for (const [tag, byShow] of Object.entries(tagged)) {
  for (const [show, episodes] of Object.entries(byShow)) {
    const agg = {};
    for (const items of episodes) {
      const seen = new Set();
      for (const it of items) {
        // Skip the tag's own vocabulary and, on topic tags, the big-company
        // names (they are visible as company tags and would top every list).
        if (seen.has(it.name) || hostsOf[show].has(it.name) || tagsOfName(it.name).includes(tag)) continue;
        if (tag in taxonomy.topics && companyOf.has(it.name.toLowerCase())) continue;
        seen.add(it.name);
        const a = (agg[it.name] ??= { name: it.name, kind: it.kind, central: 0, mentions: 0 });
        a.mentions++;
        if (it.role === 'central') a.central++;
      }
    }
    const related = Object.values(agg)
      .sort((a, b) => b.central - a.central || b.mentions - a.mentions || a.name.localeCompare(b.name))
      .slice(0, 3);
    (topics[tag] ??= {})[show] = { extractionEpisodes: episodes.length, related };
  }
}

fs.writeFileSync(OUT_TAGS, JSON.stringify(tags, null, 1) + '\n');
fs.writeFileSync(OUT_STATS, JSON.stringify({
  _doc: 'Generated by scripts/build-podcast-tags.mjs from the blog wiki extractions. Do not edit by hand.',
  tagSource,
  topics,
}, null, 1) + '\n');

for (const [show, s] of Object.entries(perShow)) {
  console.log(`${show}: ${s.episodes} episodes (${s.extraction} extraction, ${s.summary} summary), untagged ${s.untagged}`);
}
const count = {};
for (const t of Object.values(tags).flat()) count[t] = (count[t] || 0) + 1;
console.log(Object.entries(count).sort((a, b) => b[1] - a[1]).map(([t, c]) => `${t}:${c}`).join('  '));
console.log(`wrote ${path.relative(ROOT, OUT_TAGS)} and ${path.relative(ROOT, OUT_STATS)}`);

if (REPORT) {
  // Data-driven vocabulary review across ALL shows' extractions (incl. AIDB).
  const mapped = new Set([...Object.values(taxonomy.topics), ...Object.values(taxonomy.companies)].flat().map((s) => s.toLowerCase()));
  const stat = {};
  const seen = new Set();
  for (const show of [AIDB, ...podcastShows.map((s) => s.slug)]) {
    for (const b of listExtractions(show)) for (const it of readExtraction(show, b)?.items || []) {
      seen.add(it.name.toLowerCase());
      if (mapped.has(it.name.toLowerCase()) || hostsOf[show].has(it.name)) continue;
      const s = (stat[it.name] ??= { kind: it.kind, central: 0, total: 0, shows: new Set() });
      s.total++;
      if (it.role === 'central') { s.central++; s.shows.add(show); }
    }
  }
  const rows = Object.entries(stat).filter(([, s]) => s.central >= 2)
    .sort((a, b) => b[1].central * 3 + b[1].total - (a[1].central * 3 + a[1].total));
  console.log('\nTop unmapped names (central in >= 2 episodes; hosts excluded):');
  for (const [n, s] of rows.slice(0, 40)) console.log(`  ${n} [${s.kind}] central ${s.central}, mentions ${s.total}, shows ${[...s.shows].join(',')}`);
  const all = [...new Set([...Object.values(taxonomy.topics), ...Object.values(taxonomy.companies)].flat())];
  const unknown = all.filter((x) => !seen.has(x.toLowerCase()));
  console.log(`\ntaxonomy names never seen in any extraction (${unknown.length}): ${unknown.join(', ')}`);
}
